#!/bin/sh
# Creates .env with freshly generated secrets for local development.
# Safe to re-run: it never overwrites an existing .env.
set -eu

cd "$(dirname "$0")/.."

if [ -f .env ]; then
  echo ".env already exists; leaving it untouched."
  exit 0
fi

command -v openssl >/dev/null || { echo "openssl is required." >&2; exit 1; }

secret() { openssl rand -hex "$1"; }

umask 077
{
  echo "# Generated by scripts/bootstrap.sh for local development. Never commit this file."
  echo "SALEOR_VERSION=3.23"
  echo "POSTGRES_PASSWORD=$(secret 16)"
  echo "SALEOR_DB_PASSWORD=$(secret 16)"
  echo "STOREBRIDGE_DB_PASSWORD=$(secret 16)"
  echo "SALEOR_SECRET_KEY=$(secret 32)"
  printf 'SALEOR_RSA_PRIVATE_KEY="%s"\n' "$(openssl genrsa 2048 2>/dev/null)"
} > .env

echo "Created .env with new local secrets."
